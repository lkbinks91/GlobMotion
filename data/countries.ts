// Convert lat/lng to 3D spherical coordinates
export function latLngToVector3(lat: number, lng: number, radius: number = 1): [number, number, number] {
  const phi = (90 - lat) * (Math.PI / 180);
  const theta = (lng + 180) * (Math.PI / 180);
  
  const x = -(radius * Math.sin(phi) * Math.cos(theta));
  const z = radius * Math.sin(phi) * Math.sin(theta);
  const y = radius * Math.cos(phi);
  
  return [x, y, z];
}

// Find closest country to a point on the globe
export function findClosestCountry(point: { x: number; y: number; z: number }, radius: number = 1): Country | null {
  let closest: Country | null = null;
  let minDistance = Infinity;
  
  for (const country of countries) {
    const [cx, cy, cz] = latLngToVector3(country.lat, country.lng, radius);
    const distance = Math.sqrt(
      Math.pow(point.x - cx, 2) +
      Math.pow(point.y - cy, 2) +
      Math.pow(point.z - cz, 2)
    );
    
    if (distance < minDistance) {
      minDistance = distance;
      closest = country;
    }
  }
  
  // Only return if close enough (threshold for click detection)
  return minDistance < 0.3 ? closest : null;
}
